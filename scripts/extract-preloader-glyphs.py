"""Writes lib/animations/preloaderGlyphs.ts: the preloader's JM and counter glyphs as vector paths.

The preloader is drawn on a canvas in a Web Worker (so it keeps moving while the main thread is
busy), and a worker has no access to the page's web fonts. So the few glyphs it needs are baked
here from the same fonts the site loads:

    python scripts/extract-preloader-glyphs.py <Urbanist-Bold.woff2> <Geist-variable.woff2>

(next/font self-hosts them in .next/static/media/ after a build; pick the latin subsets.)
Needs fontTools and brotli (pip install fonttools brotli).
"""

import math
import sys
from pathlib import Path

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

OUT = Path(__file__).resolve().parent.parent / 'lib' / 'animations' / 'preloaderGlyphs.ts'

# The JM mark, in the logo's 520-unit-wide space (same size and spacing as the old SVG logo).
JM_FONT_SIZE = 79
JM_LETTER_SPACING = 2
JM_CENTER_X = 260
JM_MIDDLE_Y = 65
COUNTER_WEIGHT = 500


class TracePen(BasePen):
    """Collects each contour as SVG path data (after a transform) and measures its length."""

    def __init__(self, glyph_set, transform, digits):
        super().__init__(glyph_set)
        self.transform = transform
        self.digits = digits
        self.contours = []
        self._d = []
        self._len = 0.0
        self._pt = None

    def _xy(self, pt):
        return self.transform(*pt)

    def _fmt(self, pt):
        x, y = self._xy(pt)
        return f'{round(x, self.digits):g} {round(y, self.digits):g}'

    def _moveTo(self, pt):
        self._d = [f'M{self._fmt(pt)}']
        self._len = 0.0
        self._pt = self._xy(pt)

    def _lineTo(self, pt):
        p = self._xy(pt)
        self._len += math.dist(self._pt, p)
        self._pt = p
        self._d.append(f'L{self._fmt(pt)}')

    def _qCurveToOne(self, pt1, pt2):
        a, b, c = self._pt, self._xy(pt1), self._xy(pt2)
        self._len += curve_length(lambda t: tuple((1 - t) ** 2 * a[i] + 2 * (1 - t) * t * b[i] + t * t * c[i] for i in (0, 1)))
        self._pt = c
        self._d.append(f'Q{self._fmt(pt1)} {self._fmt(pt2)}')

    def _curveToOne(self, pt1, pt2, pt3):
        a, b, c, d = self._pt, self._xy(pt1), self._xy(pt2), self._xy(pt3)
        self._len += curve_length(lambda t: tuple(
            (1 - t) ** 3 * a[i] + 3 * (1 - t) ** 2 * t * b[i] + 3 * (1 - t) * t * t * c[i] + t ** 3 * d[i] for i in (0, 1)))
        self._pt = d
        self._d.append(f'C{self._fmt(pt1)} {self._fmt(pt2)} {self._fmt(pt3)}')

    def _closePath(self):
        start = self._xy(self._start)
        self._len += math.dist(self._pt, start)
        self._d.append('Z')
        self.contours.append((''.join(self._d), self._len))

    _endPath = _closePath

    def moveTo(self, pt):
        self._start = pt
        super().moveTo(pt)


def curve_length(at, steps=48):
    points = [at(i / steps) for i in range(steps + 1)]
    return sum(math.dist(points[i], points[i + 1]) for i in range(steps))


def glyph_name(font, char):
    return font.getBestCmap()[ord(char)]


def main(urbanist_path, geist_path):
    # JM: contours in the logo space, laid out like SVG text (anchor middle, baseline middle).
    urbanist = TTFont(urbanist_path)
    glyphs = urbanist.getGlyphSet()
    upm = urbanist['head'].unitsPerEm
    scale = JM_FONT_SIZE / upm
    x_height = urbanist['OS/2'].sxHeight * scale
    advances = [urbanist['hmtx'][glyph_name(urbanist, c)][0] * scale for c in 'JM']
    width = sum(advances) + JM_LETTER_SPACING
    baseline = JM_MIDDLE_Y + x_height / 2
    x = JM_CENTER_X - width / 2
    jm = []
    for char, advance in zip('JM', advances):
        origin = x
        pen = TracePen(glyphs, lambda gx, gy, o=origin: (o + gx * scale, baseline - gy * scale), 2)
        glyphs[glyph_name(urbanist, char)].draw(pen)
        jm.extend(pen.contours)
        x += advance + JM_LETTER_SPACING

    # Counter: digits and % from Geist at the counter's weight, in em units (baseline at 0).
    geist = instantiateVariableFont(TTFont(geist_path), {'wght': COUNTER_WEIGHT})
    gglyphs = geist.getGlyphSet()
    gupm = geist['head'].unitsPerEm
    cap_height = geist['OS/2'].sCapHeight / gupm
    counter = {}
    for char in '0123456789%':
        name = glyph_name(geist, char)
        pen = TracePen(gglyphs, lambda gx, gy: (gx / gupm, -gy / gupm), 4)
        gglyphs[name].draw(pen)
        counter[char] = (''.join(d for d, _ in pen.contours), geist['hmtx'][name][0] / gupm)

    lines = [
        '// Generated by scripts/extract-preloader-glyphs.py — do not edit by hand.',
        '// The preloader canvas draws from these paths because its Web Worker cannot use the page fonts.',
        '',
        f'/** The JM mark (Urbanist Bold {JM_FONT_SIZE}), one entry per contour, in the logo\'s 520-unit space. */',
        'export const JM_CONTOURS: readonly { d: string; length: number }[] = [',
    ]
    lines += [f"    {{ d: '{d}', length: {length:.2f} }}," for d, length in jm]
    lines += [
        '];',
        '',
        f'/** Bottom of the JM letters (their baseline) in the logo space. */',
        f'export const JM_BASELINE = {baseline:.2f};',
        '',
        f'/** Geist {COUNTER_WEIGHT} cap height, in em. */',
        f'export const COUNTER_CAP_HEIGHT = {cap_height:.4f};',
        '',
        f'/** Geist {COUNTER_WEIGHT} digits and %, in em with the baseline at 0 (y down). */',
        'export const COUNTER_GLYPHS: Readonly<Record<string, { d: string; advance: number }>> = {',
    ]
    lines += [f"    '{c}': {{ d: '{d}', advance: {adv:.4f} }}," for c, (d, adv) in counter.items()]
    lines += ['};', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'wrote {OUT} ({len(jm)} JM contours, lengths {[round(l) for _, l in jm]})')


if __name__ == '__main__':
    main(*sys.argv[1:3])
